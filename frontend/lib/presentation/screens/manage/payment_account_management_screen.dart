class _PaymentAccountDialog extends ConsumerStatefulWidget {
  final PaymentAccount? account;
  final Function({
    required String provider,
    String? accountNumber,
    String? suffix,
    PaymentAccount? existingAccount,
  })
  onSave;

  const _PaymentAccountDialog({this.account, required this.onSave});

  @override
  ConsumerState<_PaymentAccountDialog> createState() =>
      _PaymentAccountDialogState();
}

class _PaymentAccountDialogState extends ConsumerState<_PaymentAccountDialog> {
  final _formKey = GlobalKey<FormState>();
  String? _selectedProvider;
  final _accountNumberController = TextEditingController();
  final _suffixController = TextEditingController();
  bool _isSubmitting = false;

  @override
  void initState() {
    super.initState();
    if (widget.account != null) {
      _selectedProvider = widget.account!.provider.name;
      _accountNumberController.text = widget.account!.accountNumber ?? '';
      _suffixController.text = widget.account!.suffix ?? '';
    }
  }

  @override
  void dispose() {
    _accountNumberController.dispose();
    _suffixController.dispose();
    super.dispose();
  }

  Future<void> _submit() async {
    if (_formKey.currentState!.validate()) {
      setState(() {
        _isSubmitting = true;
      });
      try {
        await widget.onSave(
          provider: _selectedProvider!,
          accountNumber: _accountNumberController.text.isEmpty
              ? null
              : _accountNumberController.text,
          suffix: _suffixController.text.isEmpty
              ? null
              : _suffixController.text,
          existingAccount: widget.account,
        );
      } finally {
        if (mounted) {
          setState(() {
            _isSubmitting = false;
          });
        }
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final bottomInset = MediaQuery.of(context).viewInsets.bottom;

    return Container(
      decoration: const BoxDecoration(
        color: TwColors.primaryBg,
        borderRadius: BorderRadius.vertical(top: Radius.circular(28)),
      ),
      padding: EdgeInsets.fromLTRB(24, 20, 24, 24 + bottomInset),
      child: Form(
        key: _formKey,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Center(
                child: Container(
                  width: 40,
                  height: 4,
                  decoration: BoxDecoration(
                    color: TwColors.slate700,
                    borderRadius: BorderRadius.circular(2),
                  ),
                ),
              ),
              const SizedBox(height: 20),
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Text(
                    widget.account == null
                        ? 'Add Payment Account'
                        : 'Edit Payment Account',
                    style: const TextStyle(
                      color: TwColors.white,
                      fontSize: 20,
                      fontWeight: FontWeight.w700,
                    ),
                  ),
                  GestureDetector(
                    onTap: () => Navigator.pop(context),
                    child: Container(
                      width: 34,
                      height: 34,
                      decoration: BoxDecoration(
                        color: TwColors.white.withValues(alpha: 0.07),
                        borderRadius: BorderRadius.circular(10),
                        border: Border.all(color: TwColors.slate700, width: 1),
                      ),
                      child: const Icon(
                        Icons.close_rounded,
                        color: TwColors.white,
                        size: 18,
                      ),
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 24),
              DropdownButtonFormField<String>(
                value: _selectedProvider,
                decoration: InputDecoration(
                  labelText: 'Provider',
                  filled: true,
                  fillColor: Colors.black,
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(color: TwColors.slate700, width: 1),
                  ),
                  enabledBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(color: TwColors.slate700, width: 1),
                  ),
                  focusedBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: const BorderSide(
                      color: TwColors.brightGreen,
                      width: 1.5,
                    ),
                  ),
                ),
                style: const TextStyle(
                  color: TwColors.white,
                  fontSize: 14,
                  fontWeight: FontWeight.w500,
                ),
                items: PaymentProvider.values.map((provider) {
                  String displayName;
                  switch (provider) {
                    case PaymentProvider.CBE:
                      displayName = 'CBE';
                      break;
                    case PaymentProvider.TELEBIRR:
                      displayName = 'Telebirr';
                      break;
                    case PaymentProvider.DASHEN:
                      displayName = 'Dashen';
                      break;
                    case PaymentProvider.ABYSSINIA:
                      displayName = 'Abyssinia';
                      break;
                    case PaymentProvider.CBEBIRR:
                      displayName = 'CBE Birr';
                      break;
                    case PaymentProvider.M_PESA:
                      displayName = 'M-Pesa';
                      break;
                  }
                  return DropdownMenuItem(
                    value: provider.name,
                    child: Text(displayName),
                  );
                }).toList(),
                onChanged: widget.account == null
                    ? (value) {
                        setState(() {
                          _selectedProvider = value;
                        });
                      }
                    : null,
                validator: (value) =>
                    value == null ? 'Please select a provider' : null,
              ),
              const SizedBox(height: 16),
              _PaymentFormField(
                controller: _accountNumberController,
                label: 'Account Number',
                hint: 'Enter account number (optional)',
                icon: Icons.account_balance_outlined,
              ),
              const SizedBox(height: 16),
              if (_selectedProvider == 'CBE' ||
                  _selectedProvider == 'ABYSSINIA')
                _PaymentFormField(
                  controller: _suffixController,
                  label: _selectedProvider == 'CBE'
                      ? 'Suffix (8 digits)'
                      : 'Suffix (5 digits)',
                  hint: 'Enter suffix',
                  icon: Icons.numbers_outlined,
                  keyboardType: TextInputType.number,
                  validator: (value) {
                    if (value == null || value.isEmpty) {
                      return 'Please enter a suffix';
                    }
                    if (_selectedProvider == 'CBE' && value.length != 8) {
                      return 'Suffix must be 8 digits';
                    }
                    if (_selectedProvider == 'ABYSSINIA' && value.length != 5) {
                      return 'Suffix must be 5 digits';
                    }
                    return null;
                  },
                ),
              const SizedBox(height: 28),
              SizedBox(
                width: double.infinity,
                child: ElevatedButton(
                  onPressed: _isSubmitting ? null : _submit,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: TwColors.brightGreen,
                    foregroundColor: TwColors.primaryBg,
                    padding: const EdgeInsets.symmetric(horizontal: 24),
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(16),
                    ),
                    elevation: 0,
                    shadowColor: Colors.transparent,
                    minimumSize: const Size(double.infinity, 52),
                  ),
                  child: _isSubmitting
                      ? const SizedBox(
                          height: 20,
                          width: 20,
                          child: CircularProgressIndicator(
                            color: TwColors.primaryBg,
                            strokeWidth: 2,
                          ),
                        )
                      : Row(
                          mainAxisSize: MainAxisSize.min,
                          children: [
                            Icon(
                              widget.account == null
                                  ? Icons.add_rounded
                                  : Icons.check_rounded,
                              size: 20,
                            ),
                            const SizedBox(width: 8),
                            Text(
                              widget.account == null
                                  ? 'Add Account'
                                  : 'Update Account',
                              style: const TextStyle(
                                fontSize: 15,
                                fontWeight: FontWeight.w700,
                              ),
                            ),
                          ],
                        ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
