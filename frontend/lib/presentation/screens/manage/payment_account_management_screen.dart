class PaymentAccountManagementScreen extends ConsumerStatefulWidget {
  const PaymentAccountManagementScreen({super.key});

  @override
  ConsumerState<PaymentAccountManagementScreen> createState() =>
      _PaymentAccountManagementScreenState();
}

class _PaymentAccountManagementScreenState
    extends ConsumerState<PaymentAccountManagementScreen> {
  List<PaymentAccount>? _accounts;
  bool _loading = true;
  String? _error;
  String? _qrLoadingId;

  @override
  void initState() {
    super.initState();
    _loadAccounts();
  }

  Future<void> _loadAccounts() async {
    final authState = ref.read(authNotifierProvider);
    if (!authState.isAuthenticated) return;

    try {
      setState(() {
        _loading = true;
        _error = null;
      });

      final datasource = PaymentRemoteDatasource(client: http.Client());
      final accounts = await datasource.getPaymentAccounts(
        accessToken: authState.tokens!.accessToken,
      );

      setState(() {
        _accounts = accounts;
      });
    } catch (e) {
      setState(() {
        _error = e.toString();
      });
    } finally {
      setState(() {
        _loading = false;
      });
    }
  }

  void _showAddEditDialog([PaymentAccount? account]) {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (context) =>
          _PaymentAccountDialog(account: account, onSave: _saveAccount),
    );
  }

  Future<void> _saveAccount({
    required String provider,
    String? accountNumber,
    String? suffix,
    PaymentAccount? existingAccount,
  }) async {
    final authState = ref.read(authNotifierProvider);
    if (!authState.isAuthenticated) return;

    try {
      final datasource = PaymentRemoteDatasource(client: http.Client());
      final PaymentAccount savedAccount;
      if (existingAccount == null) {
        savedAccount = await datasource.createPaymentAccount(
          accessToken: authState.tokens!.accessToken,
          provider: provider,
          accountNumber: accountNumber,
          suffix: suffix,
        );
      } else {
        savedAccount = await datasource.updatePaymentAccount(
          accessToken: authState.tokens!.accessToken,
          provider: provider,
          accountNumber: accountNumber,
          suffix: suffix,
        );
      }
      if (mounted) {
        Navigator.of(context).pop();
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: const Text('Payment account saved successfully'),
            backgroundColor: TwColors.brightGreen,
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
            ),
          ),
        );
      }
      _loadAccounts();

      // Every new account receives its QR identifier in the same write; open
      // the QR right away so it can be saved or shared immediately.
      if (existingAccount == null) {
        await _openQr(savedAccount.id);
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error: ${e.toString()}'),
            backgroundColor: TwColors.red500,
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
            ),
          ),
        );
      }
    }
  }

  /// Loads the account's QR information from the backend and opens the
  /// full-screen QR view. Works for accounts created before QR support too,
  /// because the identifier is generated by the migration for every account.
  Future<void> _openQr(String accountId) async {
    if (!mounted) return;
    setState(() => _qrLoadingId = accountId);
    try {
      final info = await ref.read(qrApiProvider).accountQr(accountId);
      if (!mounted) return;
      await Navigator.of(
        context,
      ).push(MaterialPageRoute(builder: (_) => QRDisplayScreen(account: info)));
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Could not load QR code: ${e.toString()}'),
          backgroundColor: TwColors.red500,
          behavior: SnackBarBehavior.floating,
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(12),
          ),
        ),
      );
    } finally {
      if (mounted) setState(() => _qrLoadingId = null);
    }
  }

  Future<void> _deleteAccount(PaymentAccount account) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: TwColors.slate900,
        title: const Text(
          'Delete Account',
          style: TextStyle(color: TwColors.white),
        ),
        content: const Text(
          'Are you sure you want to delete this payment account?',
          style: TextStyle(color: TwColors.slate400),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(context).pop(false),
            child: const Text(
              'Cancel',
              style: TextStyle(color: TwColors.slate400),
            ),
          ),
          TextButton(
            onPressed: () => Navigator.of(context).pop(true),
            child: const Text(
              'Delete',
              style: TextStyle(color: TwColors.red500),
            ),
          ),
        ],
      ),
    );

    if (confirmed == true) {
      final authState = ref.read(authNotifierProvider);
      if (!authState.isAuthenticated) return;
      try {
        final datasource = PaymentRemoteDatasource(client: http.Client());
        await datasource.deletePaymentAccount(
          accessToken: authState.tokens!.accessToken,
          provider: account.provider.name,
        );
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: const Text('Account deleted successfully'),
              backgroundColor: TwColors.brightGreen,
              behavior: SnackBarBehavior.floating,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(12),
              ),
            ),
          );
        }
        _loadAccounts();
      } catch (e) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text('Error: ${e.toString()}'),
              backgroundColor: TwColors.red500,
              behavior: SnackBarBehavior.floating,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(12),
              ),
            ),
          );
        }
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final authState = ref.watch(authNotifierProvider);
    final canAdd = authState.role.canAddPaymentAccount;

    return Scaffold(
      backgroundColor: TwColors.primaryBg,
      body: SafeArea(
        child: Column(
          children: [
            _buildHeader(),
            Expanded(
              child: RefreshIndicator(
                onRefresh: _loadAccounts,
                color: TwColors.brightGreen,
                backgroundColor: TwColors.slate800,
                child: SingleChildScrollView(
                  physics: const AlwaysScrollableScrollPhysics(),
                  padding: const EdgeInsets.symmetric(
                    horizontal: 16,
                    vertical: 16,
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      if (canAdd)
                        GestureDetector(
                          onTap: () => _showAddEditDialog(),
                          child: Container(
                            width: double.infinity,
                            height: 50,
                            decoration: BoxDecoration(
                              color: TwColors.brightGreen,
                              borderRadius: BorderRadius.circular(14),
                            ),
                            child: const Center(
                              child: Row(
                                mainAxisSize: MainAxisSize.min,
                                children: [
                                  Icon(
                                    Icons.add_rounded,
                                    color: TwColors.slate900,
                                    size: 22,
                                  ),
                                  SizedBox(width: 8),
                                  Text(
                                    'Add Payment Account',
                                    style: TextStyle(
                                      color: TwColors.slate900,
                                      fontSize: 15,
                                      fontWeight: FontWeight.w700,
                                    ),
                                  ),
                                ],
                              ),
                            ),
                          ),
                        ),
                      const SizedBox(height: 16),
                      if (_loading)
                        const Center(
                          child: CircularProgressIndicator(
                            color: TwColors.brightGreen,
                          ),
                        )
                      else if (_error != null)
                        Center(
                          child: Padding(
                            padding: const EdgeInsets.symmetric(vertical: 60),
                            child: Column(
                              children: [
                                Icon(
                                  Icons.error_outline_rounded,
                                  size: 48,
                                  color: TwColors.red500,
                                ),
                                const SizedBox(height: 20),
                                Text(
                                  'Failed to load accounts',
                                  style: TextStyle(
                                    color: TwColors.white,
                                    fontSize: 16,
                                    fontWeight: FontWeight.w500,
                                  ),
                                ),
                                const SizedBox(height: 8),
                                Text(
                                  _error!,
                                  style: TextStyle(
                                    color: TwColors.slate400,
                                    fontSize: 14,
                                  ),
                                  textAlign: TextAlign.center,
                                ),
                                const SizedBox(height: 20),
                                GestureDetector(
                                  onTap: _loadAccounts,
                                  child: Container(
                                    padding: const EdgeInsets.symmetric(
                                      horizontal: 20,
                                      vertical: 12,
                                    ),
                                    decoration: BoxDecoration(
                                      color: TwColors.brightGreen.withValues(
                                        alpha: 0.12,
                                      ),
                                      borderRadius: BorderRadius.circular(12),
                                      border: Border.all(
                                        color: TwColors.brightGreen.withValues(
                                          alpha: 0.3,
                                        ),
                                        width: 1,
                                      ),
                                    ),
                                    child: Row(
                                      mainAxisSize: MainAxisSize.min,
                                      children: [
                                        Icon(
                                          Icons.refresh_rounded,
                                          color: TwColors.brightGreen,
                                          size: 18,
                                        ),
                                        const SizedBox(width: 8),
                                        Text(
                                          'Retry',
                                          style: TextStyle(
                                            color: TwColors.brightGreen,
                                            fontSize: 14,
                                            fontWeight: FontWeight.w600,
                                          ),
                                        ),
                                      ],
                                    ),
                                  ),
                                ),
                              ],
                            ),
                          ),
                        )
                      else if (_accounts == null || _accounts!.isEmpty)
                        Center(
                          child: Padding(
                            padding: const EdgeInsets.symmetric(vertical: 60),
                            child: Column(
                              mainAxisAlignment: MainAxisAlignment.center,
                              children: [
                                Container(
                                  padding: const EdgeInsets.all(20),
                                  decoration: BoxDecoration(
                                    color: TwColors.brightGreen.withValues(
                                      alpha: 0.1,
                                    ),
                                    shape: BoxShape.circle,
                                  ),
                                  child: Icon(
                                    Icons.account_balance_wallet_outlined,
                                    size: 48,
                                    color: TwColors.brightGreen,
                                  ),
                                ),
                                const SizedBox(height: 20),
                                Text(
                                  'No payment accounts added yet',
                                  style: TextStyle(
                                    color: TwColors.white,
                                    fontSize: 16,
                                    fontWeight: FontWeight.w500,
                                  ),
                                ),
                                const SizedBox(height: 8),
                                Text(
                                  'Add your first payment account to get started',
                                  style: TextStyle(
                                    color: TwColors.slate400,
                                    fontSize: 14,
                                  ),
                                ),
                              ],
                            ),
                          ),
                        )
                      else
                        ..._accounts!.map(
                          (account) => _AccountCard(
                            account: account,
                            isQrLoading: _qrLoadingId == account.id,
                            onViewQr: () => _openQr(account.id),
                            onEdit: () => _showAddEditDialog(account),
                            onDelete: () => _deleteAccount(account),
                          ),
                        ),
                    ],
                  ),
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildHeader() {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 16),
      decoration: BoxDecoration(
        border: Border(bottom: BorderSide(color: TwColors.slate800, width: 1)),
      ),
      child: Row(
        children: [
          GestureDetector(
            onTap: () => Navigator.of(context).pop(),
            child: Container(
              width: 36,
              height: 36,
              decoration: BoxDecoration(
                color: TwColors.slate800,
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: TwColors.slate700, width: 1),
              ),
              child: const Icon(
                Icons.arrow_back_ios_new_rounded,
                color: TwColors.white,
                size: 18,
              ),
            ),
          ),
          const SizedBox(width: 16),
          const Expanded(
            child: Text(
              'Payment Accounts',
              style: TextStyle(
                color: TwColors.white,
                fontSize: 18,
                fontWeight: FontWeight.w700,
              ),
            ),
          ),
        ],
      ),
    );
  }
}

class _AccountCard extends ConsumerWidget {
  final PaymentAccount account;
  final bool isQrLoading;
  final VoidCallback onViewQr;
  final VoidCallback onEdit;
  final VoidCallback onDelete;

  const _AccountCard({
    required this.account,
    this.isQrLoading = false,
    required this.onViewQr,
    required this.onEdit,
    required this.onDelete,
  });

  String get _providerDisplayName {
    switch (account.provider) {
      case PaymentProvider.CBE:
        return 'CBE';
      case PaymentProvider.TELEBIRR:
        return 'Telebirr';
      case PaymentProvider.DASHEN:
        return 'Dashen';
      case PaymentProvider.ABYSSINIA:
        return 'Abyssinia';
      case PaymentProvider.CBEBIRR:
        return 'CBE Birr';
      case PaymentProvider.M_PESA:
        return 'M-Pesa';
    }
  }

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final authState = ref.watch(authNotifierProvider);
    final canViewQr = authState.role.canViewQRCode;
    final canEdit = authState.role.canEditPaymentAccount;
    final canRemove = authState.role.canRemovePaymentAccount;

    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: Colors.black,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: TwColors.slate700, width: 1),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Expanded(
                child: Text(
                  _providerDisplayName,
                  style: const TextStyle(
                    color: TwColors.white,
                    fontSize: 16,
                    fontWeight: FontWeight.w600,
                  ),
                  overflow: TextOverflow.ellipsis,
                ),
              ),
            ],
          ),
          const SizedBox(height: 8),
          if (account.accountNumber != null)
            Padding(
              padding: const EdgeInsets.only(top: 8),
              child: _InfoRow(
                icon: Icons.account_balance_outlined,
                value: 'Account: ${account.accountNumber}',
              ),
            ),
          if (account.suffix != null)
            Padding(
              padding: const EdgeInsets.only(top: 8),
              child: _InfoRow(
                icon: Icons.numbers_outlined,
                value: 'Suffix: ${account.suffix}',
              ),
            ),
          if (canViewQr || canEdit || canRemove)
            Padding(
              padding: const EdgeInsets.only(top: 12),
              child: Row(
                children: [
                  if (canViewQr)
                    Expanded(
                      child: _ActionBtn(
                        icon: Icons.qr_code_2_rounded,
                        label: isQrLoading ? 'Loading…' : 'QR',
                        onTap: isQrLoading ? null : onViewQr,
                        isRemove: false,
                      ),
                    ),
                  if (canViewQr && (canEdit || canRemove))
                    const SizedBox(width: 8),
                  if (canEdit)
                    Expanded(
                      child: _ActionBtn(
                        icon: Icons.edit_outlined,
                        label: 'Edit',
                        onTap: onEdit,
                        isRemove: false,
                      ),
                    ),
                  if (canEdit && canRemove) const SizedBox(width: 8),
                  if (canRemove)
                    Expanded(
                      child: _ActionBtn(
                        icon: Icons.delete_outline,
                        label: 'Remove',
                        onTap: onDelete,
                        isRemove: true,
                      ),
                    ),
                ],
              ),
            ),
        ],
      ),
    );
  }
}

